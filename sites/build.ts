import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { sha256Hex } from '@detour/shared';

import { buildList } from './list-build';

const ROOT = resolve(import.meta.dirname, '..');
const SOURCE = join(ROOT, 'sites', 'sites.release.json');
const DEV_SOURCE = join(ROOT, 'sites', 'sites.dev.yaml');
const LIST_OUTPUT = join(ROOT, 'packages', 'extension', 'src', 'sites.json');
const ID_OUTPUT = join(ROOT, 'packages', 'extension', 'src', 'sites-id.ts');

const withDev = process.argv.includes('--dev');

if (!existsSync(SOURCE)) {
  process.stderr.write('sites.release.json: the artifact is missing; run pnpm list:sync\n');
  process.exit(1);
}

if (withDev && !existsSync(DEV_SOURCE)) {
  process.stderr.write('sites.dev.yaml: the overlay is missing\n');
  process.exit(1);
}

const overlay = withDev ? readFileSync(DEV_SOURCE, 'utf8') : undefined;
const result = buildList(JSON.parse(readFileSync(SOURCE, 'utf8')), overlay);

if (!result.ok) {
  for (const problem of result.problems) {
    process.stderr.write(`${problem}\n`);
  }

  process.exit(1);
}

const text = `${JSON.stringify(result.list, null, 2)}\n`;
const id = await sha256Hex(text);

mkdirSync(dirname(LIST_OUTPUT), { recursive: true });
writeFileSync(LIST_OUTPUT, text);
writeFileSync(
  ID_OUTPUT,
  [
    '// Generated by `pnpm list:build`. Do not edit by hand.',
    '// The SHA-256 of the bundled list body, and the identifier that a report carries.',
    `export const BUNDLED_LIST_ID = '${id}';`,
    '',
  ].join('\n'),
);

process.stdout.write(`${result.list.sites.length} sites, id ${id.slice(0, 12)}, wrote 2 files\n`);
